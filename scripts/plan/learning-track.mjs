#!/usr/bin/env node
// Validates the concept/phase map (docs/learning/concept-phase-map.json) and renders the
// learning track (docs/learning/learning-track.md). Pure node, no dependencies.
// Pure functions are exported for tests; the CLI at the bottom does the file I/O.
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

export const PHASES = ['P0', 'P1', 'P2', 'P3', 'P4', 'P5']

// Concepts the plan needs sooner than the concept map schedules them (blueprint-errata E-18,
// B1-report "Learning track"). This is planning inference, not part of the blueprint data.
export const PULL_FORWARD = {
  P0: ['state', 'split', 'testpyr', 'e2e'],
  P1: ['csp', 'ci'],
  P2: ['flags', 'testpyr'],
}

const phaseIndex = (p) => PHASES.indexOf(p)

// Returns a list of human-readable problems; empty means the map is valid.
export function validateMap(concepts) {
  const errs = []
  if (!Array.isArray(concepts)) return ['concept map must be an array']
  const byId = new Map()
  for (const c of concepts) {
    if (!c || typeof c.id !== 'string' || !c.id) { errs.push('concept without a string id'); continue }
    if (byId.has(c.id)) errs.push(`duplicate id: ${c.id}`)
    byId.set(c.id, c)
    if (phaseIndex(c.phase) === -1) errs.push(`${c.id}: unknown phase ${c.phase}`)
    if (!Number.isInteger(c.level) || c.level < 1 || c.level > 3) errs.push(`${c.id}: level must be 1-3`)
    if (!Array.isArray(c.requires)) errs.push(`${c.id}: requires must be an array`)
  }
  for (const c of byId.values()) {
    for (const r of Array.isArray(c.requires) ? c.requires : []) {
      const dep = byId.get(r)
      if (!dep) { errs.push(`${c.id}: requires unknown concept ${r}`); continue }
      if (phaseIndex(dep.phase) > phaseIndex(c.phase)) errs.push(`${c.id} (${c.phase}) requires ${r} in later phase ${dep.phase}`)
    }
  }
  // cycle detection (iterative-safe DFS with colours)
  const colour = new Map()
  const visit = (id, path) => {
    colour.set(id, 1)
    for (const r of byId.get(id).requires || []) {
      if (!byId.has(r)) continue
      if (colour.get(r) === 1) { errs.push(`cycle: ${[...path, id, r].join(' -> ')}`); continue }
      if (!colour.get(r)) visit(r, [...path, id])
    }
    colour.set(id, 2)
  }
  for (const id of byId.keys()) if (!colour.get(id)) visit(id, [])
  return errs
}

const list = (ids) => (ids.length ? ids.map((i) => `\`${i}\``).join(', ') : 'none')

// Per-phase summary used by the rendered table.
export function phaseRows(concepts) {
  const byId = new Map(concepts.map((c) => [c.id, c]))
  return PHASES.map((phase) => {
    const own = concepts.filter((c) => c.phase === phase)
    const earlier = new Set(); const same = new Set()
    for (const c of own) {
      for (const r of c.requires) {
        const dep = byId.get(r)
        if (!dep) continue
        if (dep.phase === phase) same.add(r)
        else earlier.add(r)
      }
    }
    return {
      phase,
      concepts: own,
      earlier: [...earlier],
      same: [...same],
      roots: own.filter((c) => c.requires.length === 0).map((c) => c.id),
      pullForward: PULL_FORWARD[phase] || [],
    }
  })
}

export function renderTrack(concepts) {
  const rows = phaseRows(concepts)
  const byLevel = [1, 2, 3].map((l) => concepts.filter((c) => c.level === l).length)
  const out = []
  out.push('# Learning track')
  out.push('')
  out.push('Generated by `node scripts/plan/learning-track.mjs` from `docs/learning/concept-phase-map.json`. Do not edit by hand.')
  out.push('')
  out.push(`${concepts.length} concepts across ${PHASES.length} phases (level 1: ${byLevel[0]}, level 2: ${byLevel[1]}, level 3: ${byLevel[2]}). The graph is acyclic and no prerequisite sits in a later phase.`)
  out.push('')
  out.push('## Prerequisites per phase')
  out.push('')
  out.push('"From earlier phases" are prerequisites taught by a phase before this one. "Within phase" are prerequisites taught in the same phase. "No prerequisite" are this phase\'s concepts with nothing required. "Pull forward" is planning inference (blueprint-errata E-18): concepts the plan needs sooner than the map schedules them.')
  out.push('')
  out.push('| Phase (n concepts) | From earlier phases | Within phase | No prerequisite | Pull forward (inference) |')
  out.push('|---|---|---|---|---|')
  for (const r of rows) {
    out.push(`| ${r.phase} (${r.concepts.length}) | ${list(r.earlier)} | ${list(r.same)} | ${list(r.roots)} | ${list(r.pullForward)} |`)
  }
  for (const r of rows) {
    out.push('')
    out.push(`## ${r.phase}`)
    out.push('')
    out.push('| Concept | Name | Category | Level | Requires |')
    out.push('|---|---|---|---|---|')
    for (const c of r.concepts) out.push(`| \`${c.id}\` | ${c.label} | ${c.category} | ${c.level} | ${list(c.requires)} |`)
  }
  return out.join('\n')
}

function main() {
  const src = fileURLToPath(new URL('../../docs/learning/concept-phase-map.json', import.meta.url))
  const dest = fileURLToPath(new URL('../../docs/learning/learning-track.md', import.meta.url))
  const concepts = JSON.parse(readFileSync(src, 'utf8'))
  const errs = validateMap(concepts)
  if (errs.length) { errs.forEach((e) => console.error(`error ${e}`)); process.exit(1) }
  writeFileSync(dest, renderTrack(concepts) + '\n')
  console.log(`${concepts.length} concepts, ${PHASES.length} phases; wrote docs/learning/learning-track.md`)
}

if (process.argv[1] === fileURLToPath(import.meta.url)) main()
