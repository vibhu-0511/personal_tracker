#!/usr/bin/env node
// Extracts the readable text of docs/forge-blueprint.html into docs/plan/blueprint.txt so the
// research swarm can re-read the agreed design without parsing HTML. Re-run after editing the blueprint.
import { readFileSync, writeFileSync } from 'node:fs'

const SRC = 'docs/forge-blueprint.html'
const OUT = 'docs/plan/blueprint.txt'
const ENT = { '&amp;': '&', '&lt;': '<', '&gt;': '>', '&quot;': '"', '&#39;': "'", '&nbsp;': ' ' }

export function htmlToText(html) {
  const start = html.indexOf('<body>')
  const end = html.indexOf('<script>')
  let body = html.slice(start === -1 ? 0 : start, end === -1 ? undefined : end)
  body = body.replace(/<style[\s\S]*?<\/style>/g, '').replace(/<svg[\s\S]*?<\/svg>/g, '[diagram]')
  body = body.replace(/<(h2|h3)[^>]*>/g, '\n## ').replace(/<(tr|li|p|figcaption|div class="eyebrow")[^>]*>/g, '\n')
  body = body.replace(/<\/t[dh]>/g, ' | ').replace(/<[^>]+>/g, '')
  body = body.replace(/&(amp|lt|gt|quot|nbsp|#39);/g, (m) => ENT[m])
  return body.split('\n').map((l) => l.replace(/\s+/g, ' ').trim()).filter(Boolean).join('\n')
}

if (process.argv[1] === new URL(import.meta.url).pathname) {
  const text = htmlToText(readFileSync(SRC, 'utf8'))
  writeFileSync(OUT, `# Clean text of ${SRC} (generated by scripts/plan/blueprint-text.mjs)\n\n${text}\n`)
  console.log(`wrote ${OUT} (${text.split('\n').length} lines)`)
}
